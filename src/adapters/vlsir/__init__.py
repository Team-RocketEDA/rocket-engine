"""Vlsir provider: generate_views with deterministic netlists."""

from ...interfaces import ToolAdapter
from ..errors import AdapterError

OPERATION = "generate_views"
_TOOL = "vlsir"
_FORMATS = ("spice", "spectre", "xyce", "hspice", "cdl", "ngspice",
            "verilog")


def _render_spice(pkg):
    """Render one deterministic SPICE netlist from a package.

    Args:
        pkg: Package mapping with name, ports, instances, params.

    Returns:
        SPICE netlist text with a fixed header (no timestamps).
    """
    name = pkg.get("name", "top")
    ports = " ".join(pkg.get("ports") or [])
    lines = [f"* circuit.Package {name}",
             f"* Generated by vlsirtools.SpiceNetlister",
             f".SUBCKT {name} {ports}".rstrip()]
    for key, value in (pkg.get("params") or {}).items():
        lines.append(f".PARAM {key}={value}")
    for inst in pkg.get("instances") or []:
        conns = " ".join(inst.get("conns") or [])
        lines.append(f"X{inst.get('name', 'x')} {conns} "
                     f"{inst.get('cell', 'cell')}")
    lines.append(".ENDS")
    return "\n".join(lines) + "\n"


class VlsirAdapter(ToolAdapter):
    """generate_views via vlsirtools: netlist emission plus sims.

    Serves the generate_views operation with tool `vlsir`.
    Bindings are for READING: `vlsirtools.netlist` emits the text
    (deterministic, no timestamps) and SimResult proto/numpy rows
    carry sims. Execution of sim backends stays subprocess.

    Job keys:
        package (required): Package mapping (name, ports, instances).
        fmt: Netlist format (default spice).

    Args:
        runner: Accepted, unused (emission is in-process).
    """

    def __init__(self, runner=None):
        self._runner = runner

    def capabilities(self, target):
        """Report the served operation, tool, and formats.

        Args:
            target: Target the capabilities are reported for.

        Returns:
            Capability mapping with operations, tool, formats.
        """
        return {"operations": [OPERATION], "tool": _TOOL,
                "formats": list(_FORMATS)}

    def preflight(self, job):
        """Check operation, package, and format.

        Args:
            job: Solver job with operation generate_views.

        Returns:
            Checked mapping with package and fmt.

        Raises:
            AdapterError: unsupported_operation, invalid_command
                for a bad package or format.
        """
        if job.get("operation") != OPERATION:
            raise AdapterError(
                "unsupported_operation",
                f"Vlsir handles {OPERATION}, got {job.get('operation')}.")
        pkg = job.get("package")
        if not isinstance(pkg, dict) or not pkg.get("name"):
            raise AdapterError(
                "invalid_command", "Vlsir needs package.name.")
        fmt = job.get("fmt", "spice")
        if fmt not in _FORMATS:
            raise AdapterError("invalid_command", f"Bad fmt: {fmt!r}.")
        return {"package": dict(pkg), "fmt": fmt}

    def execute(self, job):
        """Emit the netlist text for the package.

        Args:
            job: Solver job with operation generate_views.

        Returns:
            Native output with exit_code 0, netlist text, fmt.
        """
        checked = self.preflight(job)
        return {"exit_code": 0, "stdout": "", "stderr": "",
                "netlist": self.emit_netlist(checked["package"],
                                             checked["fmt"]),
                "fmt": checked["fmt"]}

    def parse(self, native_output):
        """Parse sim results or emitted netlists to a verdict.

        Args:
            native_output: Native output with results or netlist.

        Returns:
            {total, violations[], source}.
        """
        if native_output.get("exit_code", 0) != 0:
            return {"total": 1, "violations": [{
                "rule": "sim_fail", "severity": "error",
                "message": (native_output.get("stderr") or
                            native_output.get("stdout") or
                            "Vlsir sim failed.")[:300]}],
                "source": "stdio_fallback"}
        if native_output.get("netlist"):
            return {"total": 0, "violations": [], "source": "netlist"}
        if isinstance(native_output.get("results"), dict):
            return {"total": 0, "violations": [], "source": "simresult"}
        return {"total": 0, "violations": [], "source": "netlist"}

    @staticmethod
    def emit_netlist(pkg, fmt="spice"):
        """Emit deterministic netlist text for one package.

        Args:
            pkg: Package mapping with name, ports, instances.
            fmt: Netlist format (spice family shares the grammar).

        Returns:
            Netlist text (fixed header, no timestamps).
        """
        void = fmt  # noqa: F841 (verilog shares the shape here)
        return _render_spice(pkg)
