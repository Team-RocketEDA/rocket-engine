def test_ngspice_converts_runner_errors(tmp_path):
    from rocket_engine.adapters.ngspice import NgspiceAdapter  # RED: missing adapter
    from rocket_engine.execution.errors import ExecutionError

    netlist = tmp_path / "tb.spice"
    netlist.write_text("V1 in 0 1.8\n")

    class PreflightBoom:
        def preflight(self):
            raise ExecutionError("runner_unavailable", "boom")

    class RunBoom:
        def preflight(self):
            return {"ready": True}

        def run(self, *args, **kwargs):
            raise ExecutionError("runner_unavailable", "boom")

    bindir = tmp_path / "fakebin"
    bindir.mkdir()
    (bindir / "ngspice").write_text("")
    job = _job([netlist], tmp_path, tool_dir=str(bindir))
    cases = [
        (NgspiceAdapter(runner=PreflightBoom()), "preflight"),
        (NgspiceAdapter(runner=RunBoom()), "execute"),
    ]
    for adapter, method in cases:
        try:
            getattr(adapter, method)(job)
        except Exception as exc:
            assert type(exc).__name__ == "AdapterError", type(exc).__name__
            assert exc.code == "runner_unavailable"
        else:
            raise AssertionError(f"expected converted AdapterError from {method}")


