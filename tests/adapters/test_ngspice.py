def _job(sources, tmp_path, **over):
    workdir = tmp_path / "work"
    workdir.mkdir(exist_ok=True)
    job = {
        "operation": "run_spice",
        "sources": [str(s) for s in sources],
        "workdir": str(workdir),
        "measurements": [
            {"name": "vout", "expr": "v(out)", "unit": "V",
             "min": 1.19, "max": 1.21},
        ],
    }
    job.update(over)
    return job


def _native(stdout, measurements=None, exit_code=0, stderr=""):
    return {
        "exit_code": exit_code,
        "stdout": stdout,
        "stderr": stderr,
        "log": "",
        "deck": "ngspice_deck.spice",
        "sources": ["tb.spice"],
        "measurements": (
            list(measurements)
            if measurements is not None
            else list(CANNED_SMOKE_MEASUREMENTS)
        ),
    }


class FakeRunner:
    def __init__(self, stdout, exit_code=0):
        self._stdout = stdout
        self._exit_code = exit_code
        self.seen = {}

    def preflight(self):
        return {"ready": True}

    def run(self, command, workdir, timeout_s=120, extra_binds=()):
        self.seen["command"] = command
        self.seen["workdir"] = workdir
        self.seen["timeout_s"] = timeout_s
        self.seen["extra_binds"] = extra_binds
        return subprocess.CompletedProcess(command, self._exit_code, self._stdout, "")


def _tiny_pdk(tmp_path, files=None):
    src = tmp_path / "tiny_pdk_src"
    (src / "libs.tech" / "combined").mkdir(parents=True)
    (src / "libs.tech" / "combined" / "sky130.lib.spice").write_text(
        "* tiny model lib\n.lib tt\n.ends\n"
    )
    for rel in files or []:
        target = src / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text("* tiny\n")
    return src


def _pdk_job(tmp_path, engine_root, revision="r1", **over):
    from rocket_engine.interfaces.pdks import register_pdk

    register_pdk(_tiny_pdk(tmp_path), "sky130a", revision, engine_root=engine_root)
    netlist = tmp_path / "tb.spice"
    netlist.write_text("V1 in 0 1.8\nR1 in out 1k\nR2 out 0 2k\n")
    job = _job([netlist], tmp_path)
    job["pdk"] = {
        "id": "sky130a",
        "revision": revision,
        "engine_root": str(engine_root),
    }
    job.update(over)
    return job


def _find_sky130_model():
    try:
        from rocket_engine.interfaces.paths import slugify
        from rocket_engine.interfaces.pdks import list_pdks, resolve_deck
    except Exception:
        return None
    try:
        entries = list_pdks()
    except Exception:
        return None
    want_rev = os.environ.get("SKY130_PDK_REVISION")
    candidates = [e for e in entries
                  if slugify(e.get("id") or "") == "sky130a"]
    if want_rev:
        candidates = [e for e in candidates if e.get("revision") == want_rev]
    if not candidates:
        return None
    entry = sorted(candidates, key=lambda e: e["revision"])[0]
    try:
        hit = resolve_deck(entry["id"], entry["revision"], MODEL_REL)
    except Exception:
        return None
    path = hit.get("path")
    if not path or not Path(path).is_file():
        return None
    return entry, path


