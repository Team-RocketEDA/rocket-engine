#!/usr/bin/env bash
# BUILD-LOCAL stage 4: stage the engine's shippable outputs for
# the super-repo bundle build.
#
# Copies the provisioned tools dir and, when present, the
# engine store into a destination layout, and writes a manifest
# (layout version + tool pins parsed from the provisioner,
# single source). The super-repo build.sh (integration-repo
# owned) bundles this layout; DOCKER-DEPLOY consumes it for the
# one-container recipe. `engine/`, `fuel/`, `ui/dist/` come
# from their own submodules, not from this script.
#
# Usage:
#   scripts/collect.sh --check        # verify sources, print plan
#   scripts/collect.sh --dest <dir>   # stage the layout under <dir>
#
# Honors:
#   TOOLS_DIR       provisioned tools (default: $ROOT/.tools)
#   ROCKETEDA_HOME  engine store (default: $ROOT/.stores/rocketeda)
#
# Layout written under <dir> (see docs/build-local.md):
#   tools/        copy of TOOLS_DIR (the install directory)
#   stores/       copy of ROCKETEDA_HOME when present (skipped
#                 openly when absent, never faked)
#   manifest.txt  layout version + pins + source paths

set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TOOLS_DIR="${TOOLS_DIR:-$ROOT/.tools}"
ROCKETEDA_HOME="${ROCKETEDA_HOME:-$ROOT/.stores/rocketeda}"
PROV="$ROOT/scripts/provision_toolchain.sh"
LAYOUT_VERSION=1

usage() {
    echo "usage: collect.sh [--check|--dest <dir>]" >&2
    exit 2
}

pin_of() {  # NAME — single-source pin from the provisioner
    grep -m1 -o -E "^$1=\"[^\"]+\"" "$PROV" | cut -d'"' -f2
}

plan() {
    echo "tools_source=$TOOLS_DIR"
    if [ -d "$ROCKETEDA_HOME" ]; then
        echo "store_source=$ROCKETEDA_HOME"
    else
        echo "store_source=absent (stores/ skipped)"
    fi
    echo "oss_cad_suite_pin=$(pin_of OSS_CAD_SUITE_PIN)"
    echo "librelane_pin=$(pin_of LIBRELANE_PIN)"
    echo "opensta_pin=$(pin_of OPENSTA_PIN)"
}

check() {
    if [ ! -d "$TOOLS_DIR" ]; then
        echo "collect.sh: no provisioned tools at $TOOLS_DIR" >&2
        echo "next: run scripts/provision_toolchain.sh --install (or set TOOLS_DIR), then retry" >&2
        return 1
    fi
    plan
    return 0
}

collect() {  # dest
    local dest="$1"
    check >/dev/null || return 1
    mkdir -p "$dest/tools" || return 1
    cp -a "$TOOLS_DIR/." "$dest/tools/" || return 1
    if [ -d "$ROCKETEDA_HOME" ]; then
        mkdir -p "$dest/stores" || return 1
        cp -a "$ROCKETEDA_HOME/." "$dest/stores/" || return 1
        store_src="$ROCKETEDA_HOME"
    else
        echo "collect.sh: no engine store at $ROCKETEDA_HOME (stores/ skipped)"
        store_src="absent"
    fi
    {
        echo "# rocketeda engine bundle manifest (generated by scripts/collect.sh; do not hand-edit)."
        echo "layout_version=$LAYOUT_VERSION"
        echo "collected_utc=$(date -u +%Y-%m-%dT%H:%M:%SZ)"
        echo "tools_source=$TOOLS_DIR"
        echo "store_source=$store_src"
        echo "oss_cad_suite_pin=$(pin_of OSS_CAD_SUITE_PIN)"
        echo "librelane_pin=$(pin_of LIBRELANE_PIN)"
        echo "opensta_pin=$(pin_of OPENSTA_PIN)"
        echo "opensta_short=$(pin_of OPENSTA_PIN | cut -c1-7)"
        echo "cudd_pin=$(pin_of CUDD_PIN)"
        echo "xyce_ref=$(pin_of XYCE_REF)"
        echo "trilinos_ref=$(pin_of TRILINOS_REF)"
        echo "openems_ref=$(pin_of OPENEMS_REF)"
        echo "csxcad_ref=$(pin_of CSXCAD_REF)"
        echo "pymeep_pin=$(pin_of PYMEEP_PIN)"
        echo "magic_ref=$(pin_of MAGIC_REF)"
        echo "netgen_ref=$(pin_of NETGEN_REF)"
        echo "klayout_pin=$(pin_of KLAYOUT_PIN)"
        echo "ngspice_pin=$(pin_of NGSPICE_PIN)"
        echo "xschem_ref=$(pin_of XSCHEM_REF)"
        echo "cace_pin=$(pin_of CACE_PIN)"
        echo "devsim_pin=$(pin_of DEVSIM_PIN)"
    } >"$dest/manifest.txt" || return 1
    echo "collect.sh: staged $dest (tools/ + manifest.txt$([ "$store_src" = "absent" ] || echo ", stores/"))"
    return 0
}

MODE="${1:---check}"
case "$MODE" in
    --check)
        check
        exit $?
        ;;
    --dest)
        [ -n "${2:-}" ] || usage
        collect "$2"
        exit $?
        ;;
    *)
        usage
        ;;
esac
